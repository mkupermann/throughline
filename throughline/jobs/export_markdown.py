#: Environment variable naming the directory the export may write inside.
#: Defaults to the user's home. The API needs a boundary because it has no
#: authentication: everything else it exposes is read-only, and an
#: unconstrained destination would turn it into a write-anywhere primitive.
_ROOT_ENV = "THROUGHLINE_EXPORT_ROOT"

#: Environment variable carrying the destination for a service-triggered run,
#: so a request body never has to reach the command line.
DEST_ENV = "THROUGHLINE_EXPORT_OUT"


def destination_from(argv_out: str | None) -> str:
    """The destination, from the command line or from the environment.

    A service-triggered run puts the path in ``THROUGHLINE_EXPORT_OUT``
    rather than on the command line, so the job registry keeps its
    guarantee that no request body ever becomes argv.
    """
    for candidate in (argv_out, os.environ.get(DEST_ENV)):
        if candidate and candidate.strip():
            return candidate.strip()
    raise ValueError(f"No destination given: neither --out nor {DEST_ENV}.")


def export_root() -> Path:
    """The directory the export is confined to."""
    configured = os.environ.get(_ROOT_ENV, "").strip()
    return Path(configured).expanduser().resolve() if configured else Path.home().resolve()


def resolve_destination(raw: str, *, root: Path | None = None) -> Path:
    """Validate a caller-supplied destination and return it resolved.

    Refuses anything that is not an absolute path inside *root*, and
    anything that names an existing file. Symlinks are resolved before the
    containment check, so a link inside the root pointing out of it does
    not get through.
    """
    boundary = (root or export_root()).expanduser().resolve()
    text = (raw or "").strip()
    if not text:
        raise ValueError("No destination given.")

    candidate = Path(text).expanduser()
    if not candidate.is_absolute():
        raise ValueError(f"The destination must be an absolute path: {text}")

    resolved = Path(os.path.normpath(candidate))
    # resolve() follows symlinks on the parts that exist, which is what the
    # containment check has to see; strict=False keeps a not-yet-created
    # destination legal.
    resolved = resolved.resolve()
    if resolved != boundary and boundary not in resolved.parents:
        raise ValueError(f"The destination is outside {boundary}: {resolved}")
    if resolved.is_file():
        raise ValueError(f"The destination is a file, not a directory: {resolved}")
    return resolved


def list_directory(raw: str | None, *, root: Path | None = None) -> dict[str, Any]:
    """List the immediate subdirectories of *raw* (or the export root).

    Backs an in-app folder browser rather than a native OS dialog: the API
    process may be running inside a Linux container with no display at all
    (Docker Compose's `web` service, for one), where nothing server-side can
    ever open the host's real file picker. Browsing the confined root itself
    needs no display and works identically in a container or a native
    install — the same containment rule as `resolve_destination`, except a
    browse target must already exist, where a destination need not.
    """
    boundary = (root or export_root()).expanduser().resolve()
    boundary.mkdir(parents=True, exist_ok=True)

    text = (raw or "").strip()
    target = Path(text).expanduser().resolve() if text else boundary
    if target != boundary and boundary not in target.parents:
        raise ValueError(f"The path is outside {boundary}: {target}")
    if not target.is_dir():
        raise ValueError(f"Not a directory: {target}")

    # Dotfiles/dirs are noise for choosing an export destination (`.git`,
    # `.throughline-export.json` from a previous run) and never useful here.
    dirs = sorted(
        (p for p in target.iterdir() if p.is_dir() and not p.name.startswith(".")),
        key=lambda p: p.name.lower(),
    )
    parent = target.parent if target != boundary else None
    return {
        "path": str(target),
        "root": str(boundary),
        "parent": str(parent) if parent is not None else None,
        "dirs": [{"name": p.name, "path": str(p)} for p in dirs],
    }


#: Record of what the last export wrote, kept in the destination itself.
#: Without it a re-run cannot tell its own stale output from the person's own
#: notes, and must either leave orphans behind or delete things it never made.
MANIFEST_NAME = ".throughline-export.json"


def read_manifest(out: Path) -> set[str]:
    """Relative paths the previous export wrote, or an empty set."""
    try:
        payload = json.loads((out / MANIFEST_NAME).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    files = payload.get("files")
    return {str(f) for f in files} if isinstance(files, list) else set()


def write_manifest(out: Path, paths: set[str]) -> None:
    (out / MANIFEST_NAME).write_text(
        json.dumps({"version": 1, "files": sorted(paths)}, ensure_ascii=False, indent=1),
        encoding="utf-8",
    )


def write_if_changed(path: Path, text: str) -> bool:
    """Write *text* to *path* only when it differs. Returns True if written.

    The destination is often a synced folder. Rewriting bytes that did not
    change makes the sync client re-upload the whole export and makes every
    file's timestamp useless as a record of when anything actually changed.
    """
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except (OSError, ValueError):
        pass
    path.write_text(text, encoding="utf-8")
    return True


def prune(out: Path, previous: set[str], current: set[str]) -> int:
    """Delete files the last export wrote and this one did not.

    Only paths named in the previous manifest are eligible. Anything the
    person put in the destination themselves is untouched, whatever it is
    called and wherever it sits.
    """
    removed = 0
    for relative in sorted(previous - current):
        target = out / relative
        try:
            if target.is_file():
                target.unlink()
                removed += 1
        except OSError:
            continue
    # Clean up folders this export emptied, never one that still holds anything.
    for relative in sorted({str(Path(r).parent) for r in previous - current}, reverse=True):
        folder = out / relative
        if folder != out and folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    return removed


def export_corpus(
    out: Path | str,
    conversations: list[dict[str, Any]],
    load_messages: Callable[[int], list[dict[str, Any]]],
    load_memory: Callable[[str], list[dict[str, Any]]],
    *,
    tool_output: int = 0,
    split_bytes: int = DEFAULT_SPLIT_BYTES,
    redact: bool = False,
    memory: bool = True,
    on_project: Callable[[str, int, int], None] | None = None,
) -> dict[str, Any]:
    """Write *conversations* to *out* and report what was written.

    The two loaders are injected rather than reached for, so the same
    export runs behind the CLI, behind the API, and in a test with no
    database anywhere near it.
    """
    out = Path(out).expanduser()
    out.mkdir(parents=True, exist_ok=True)

    previous = read_manifest(out)
    produced: set[str] = set()
    changed: set[Path] = set()
    stats: list[dict[str, Any]] = []
    try:
        files = _write_projects(
            out,
            conversations,
            load_messages,
            load_memory,
            stats,
            produced,
            changed,
            tool_output=tool_output,
            split_bytes=split_bytes,
            redact=redact,
            memory=memory,
            on_project=on_project,
        )
    except Exception as exc:
        # A half-written export is not a disaster: the database is still the
        # archive, and re-running rewrites. A half-written export that *reads*
        # as a finished one is — so the index says what happened before the
        # failure propagates.
        write_index(out, stats, failure=f"{type(exc).__name__}: {exc}")
        # A failed run must not delete the previous run's files: what it did
        # not write this time it may simply never have reached.
        write_manifest(out, previous | produced)
        raise

    index = write_index(out, stats, changed=changed)
    produced.add(index.relative_to(out).as_posix())
    files += 1

    removed = prune(out, previous, produced)
    write_manifest(out, produced)

    return {
        "out": str(out),
        "projects": len(stats),
        "sessions": sum(s["sessions"] for s in stats),
        "files": files,
        "written": len(changed),
        "unchanged": files - len(changed),
        "removed": removed,
        "per_project": stats,
    }


def _write_projects(
    out: Path,
    conversations: list[dict[str, Any]],
    load_messages: Callable[[int], list[dict[str, Any]]],
    load_memory: Callable[[str], list[dict[str, Any]]],
    stats: list[dict[str, Any]],
    produced: set[str],
    changed: set[Path],
    *,
    tool_output: int,
    split_bytes: int,
    redact: bool,
    memory: bool,
    on_project: Callable[[str, int, int], None] | None,
) -> int:
    """Write every project folder, appending to *stats* as it goes.

    *stats* is passed in rather than returned so a caller that catches a
    failure still knows what got written before it.
    """
    files = 0
    for folder_name, convs in sorted(group_by_folder(conversations).items()):
        sections: list[tuple[datetime, str]] = []
        for conv in convs:
            rendered = render_session(conv, load_messages(conv["id"]), tool_output, redact=redact)
            if rendered:
                sections.append((conv["started_at"], rendered))
        if not sections:
            continue

        folder = out / folder_name
        folder.mkdir(parents=True, exist_ok=True)
        written = write_parts(folder, folder_name, sections, split_bytes, changed)
        produced.update(p.relative_to(out).as_posix() for p in written)
        files += len(written)

        if memory:
            # One folder can hold more than one project_name; collect the
            # memory filed under each of them, oldest first.
            chunks: list[dict[str, Any]] = []
            for name in dict.fromkeys(c.get("project_name") or "" for c in convs):
                chunks.extend(load_memory(name))
            # created_at alone leaves ties to the database's whim, and a
            # differently-ordered Memory.md reads as a change that is not one.
            chunks.sort(key=lambda c: (c["created_at"], c.get("id") or 0))
            memory_file = write_memory(folder, folder_name, chunks, redact=redact, changed=changed)
            if memory_file:
                produced.add(memory_file.relative_to(out).as_posix())
                files += 1

        stats.append(
            {
                "project": folder_name,
                "entry": written[0].stem,
                "sessions": len(sections),
                "files": len(written),
                "first": sections[0][0],
                "last": sections[-1][0],
            }
        )
        if on_project:
            on_project(folder_name, len(sections), len(written))

    return files


def build_parser() -> argparse.ArgumentParser:
    """The command-line surface, separate from running it."""
    parser = argparse.ArgumentParser(
        prog="throughline export-markdown",
        description="Export the stored corpus as a Markdown vault, one folder per project.",
    )
    parser.add_argument(
        "--out",
        default=None,
        help="Destination directory (created if missing). Falls back to $THROUGHLINE_EXPORT_OUT.",
    )
    parser.add_argument("--project", default=None, help="Export a single project instead of all.")
    parser.add_argument("--since", default=None, help="Only sessions started on or after this date (YYYY-MM-DD).")
    parser.add_argument(
        "--include-generated",
        action="store_true",
        help="Also export machine-generated conversations (default: human sessions only).",
    )
    parser.add_argument(
        "--tool-output",
        type=int,
        default=0,
        help="Characters of each tool result to include, in a collapsed block (default: 0, omit them).",
    )
    parser.add_argument(
        "--split-bytes",
        type=int,
        default=DEFAULT_SPLIT_BYTES,
        help=f"Split a project into monthly files above this size (default: {DEFAULT_SPLIT_BYTES}).",
    )
    parser.add_argument("--no-memory", action="store_true", help="Skip the per-project Memory.md file.")
    parser.add_argument(
        "--redact",
        action="store_true",
        help="Run every exported text through the PII pass (keys, tokens, emails, home paths).",
    )
    return parser


#: Options a service-triggered run passes through the environment, so the
#: fixed job command line never has to carry a caller's values.
_ENV_OPTIONS = {
    "project": "THROUGHLINE_EXPORT_PROJECT",
    "since": "THROUGHLINE_EXPORT_SINCE",
    "include_generated": "THROUGHLINE_EXPORT_INCLUDE_GENERATED",
    "redact": "THROUGHLINE_EXPORT_REDACT",
    "tool_output": "THROUGHLINE_EXPORT_TOOL_OUTPUT",
    "no_memory": "THROUGHLINE_EXPORT_NO_MEMORY",
}


def _env_flag(name: str) -> bool:
    return os.environ.get(name, "").strip().lower() in {"1", "true", "yes", "on"}


def options_from(args: argparse.Namespace) -> dict[str, Any]:
    """Resolve every option from the command line, then the environment.

    An explicit flag always wins. A malformed environment value is ignored
    rather than fatal: the run that matters is the one the person asked
    for, and refusing it over an unparseable number nobody typed would be
    the wrong trade.
    """
    try:
        env_tool_output = int(os.environ.get(_ENV_OPTIONS["tool_output"], "") or 0)
    except ValueError:
        env_tool_output = 0

    return {
        "out": destination_from(args.out),
        "project": args.project or (os.environ.get(_ENV_OPTIONS["project"], "").strip() or None),
        "since": args.since or (os.environ.get(_ENV_OPTIONS["since"], "").strip() or None),
        "include_generated": args.include_generated or _env_flag(_ENV_OPTIONS["include_generated"]),
        "redact": args.redact or _env_flag(_ENV_OPTIONS["redact"]),
        "tool_output": args.tool_output or env_tool_output,
        "split_bytes": args.split_bytes,
        "memory": not (args.no_memory or _env_flag(_ENV_OPTIONS["no_memory"])),
    }


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    try:
        opts = options_from(args)
        out = Path(opts["out"]).expanduser()
        out.mkdir(parents=True, exist_ok=True)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    except OSError as exc:
        print(f"ERROR: cannot create {opts['out']}: {exc}", file=sys.stderr)
        return 2

    try:
        conn = psycopg2.connect(**db_config())
    except psycopg2.Error as exc:
        print(f"ERROR: database unreachable: {exc}", file=sys.stderr)
        return 1

    try:
        conversations = fetch_conversations(
            conn,
            include_generated=opts["include_generated"],
            project=opts["project"],
            since=opts["since"],
        )
        if not conversations:
            print("Nothing to export for the given filters.", file=sys.stderr)
            return 0

        summary = export_corpus(
            out,
            conversations,
            lambda cid: fetch_messages(conn, cid),
            lambda name: fetch_memory(conn, name),
            tool_output=opts["tool_output"],
            split_bytes=opts["split_bytes"],
            redact=opts["redact"],
            memory=opts["memory"],
            on_project=lambda name, sessions, files: print(f"{name}: {sessions} sessions -> {files} file(s)"),
        )
        print(
            f"\n{summary['projects']} projects, {summary['files']} files in {summary['out']}\n"
            f"{summary['written']} written, {summary['unchanged']} unchanged, {summary['removed']} removed"
        )
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
