def group_by_folder(conversations: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    """Bucket conversations by the folder they will be written to.

    Keyed by the folder name rather than the raw ``project_name``, because
    more than one name can sanitise to the same folder — ``project_name``
    is a generated column that yields ``unknown`` for a NULL path and an
    empty string for a path ending in a separator, and both become the
    folder ``unknown``. Keying by the raw name gives each a bucket, and
    the second one to be written silently overwrites the first.

    Each bucket comes back in chronological order, which merging two
    buckets would otherwise break.
    """
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for conv in conversations:
        grouped[safe_name(conv.get("project_name"))].append(conv)
    for bucket in grouped.values():
        bucket.sort(key=lambda c: (c["started_at"], c["id"]))
    return dict(grouped)


def write_parts(
    folder: Path,
    project: str,
    sections: list[tuple[datetime, str]],
    split_bytes: int,
    changed: set[Path] | None = None,
) -> list[Path]:
    """Write a project's sections, splitting into parts once they get large.

    A single file is the readable default. Splitting only kicks in when
    the whole project would land above ``split_bytes``, and each part
    then stays a contiguous stretch of time — sessions are never
    reordered, and a part is closed only when adding the next session
    would push it past the cap. Splitting on calendar months instead
    would be tidier to name and useless in practice: a month in which
    you worked every day still produces a file no editor wants to open.
    """
    total = sum(len(s.encode("utf-8")) for _, s in sections)

    def frontmatter(scope: str, count: int) -> str:
        # No run timestamp here on purpose. Stamping every project file with
        # the moment the export ran would change all of them on every run,
        # which defeats writing only what changed and makes each file's own
        # modification time meaningless. The run's date lives in README.md.
        return (
            "---\n"
            f'title: "{project}"\n'
            "tags: [throughline, export]\n"
            f'project: "{project}"\n'
            "---\n\n"
            f"# {project}\n\n"
            f"{count} sessions, oldest first{scope}.\n\n---\n\n"
        )

    written: list[Path] = []
    if total <= split_bytes or len(sections) < 2:
        path = folder / f"{safe_name(project)}.md"
        if (
            write_if_changed(path, frontmatter("", len(sections)) + "\n".join(s for _, s in sections))
            and changed is not None
        ):
            changed.add(path)
        return [path]

    parts: list[list[tuple[datetime, str]]] = [[]]
    size = 0
    for when, section in sections:
        weight = len(section.encode("utf-8"))
        if parts[-1] and size + weight > split_bytes:
            parts.append([])
            size = 0
        parts[-1].append((when, section))
        size += weight

    # Every part carries its index, not just the date it opens on. Naming
    # by date alone reads better but breaks the moment one busy day fills
    # two parts: they collide, and disambiguating only the repeats leaves
    # "Obsidian 2026-03-26 (03)" sorting ahead of "Obsidian 2026-03-26" in
    # every file listing. The index sorts the parts in the order they were
    # written, which is the order they should be read.
    for index, part in enumerate(parts, start=1):
        first, last = part[0][0], part[-1][0]
        span = f" · {first:%Y-%m-%d} to {last:%Y-%m-%d}"
        path = folder / f"{safe_name(project)} {index:02d} {first:%Y-%m-%d}.md"
        if write_if_changed(path, frontmatter(span, len(part)) + "\n".join(s for _, s in part)) and changed is not None:
            changed.add(path)
        written.append(path)
    return written


def write_memory(
    folder: Path, project: str, chunks: list[dict], *, redact: bool = False, changed: set[Path] | None = None
) -> Path | None:
    if not chunks:
        return None
    lines = [
        "---",
        f'title: "{project} — Memory"',
        "tags: [throughline, memory]",
        "---",
        "",
        f"# {project} — extracted memory\n",
        f"{len(chunks)} active entries, oldest first.\n",
    ]
    for chunk in chunks:
        when = chunk["created_at"].strftime("%Y-%m-%d %H:%M")
        tags = " ".join(f"#{t}" for t in (chunk.get("tags") or []) if t)
        lines.append(f"## {when} · {chunk['category']}\n")
        lines.append(prose(chunk["content"].strip(), redact))
        if tags:
            lines.append(f"\n{tags}")
        lines.append("")
    path = folder / "Memory.md"
    if write_if_changed(path, "\n".join(lines)) and changed is not None:
        changed.add(path)
    return path


def write_index(out: Path, stats: list[dict], failure: str | None = None, changed: set[Path] | None = None) -> Path:
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "---",
        'title: "Throughline"',
        "tags: [throughline, export]",
        f"exported: {stamp}",
        "---",
        "",
        "# Throughline",
        "",
        f"Throughline export taken on {stamp}. {len(stats)} projects, {sum(s['sessions'] for s in stats):,} sessions.",
        "",
        *(
            [
                f"> **This export is incomplete.** It stopped with: `{failure}`",
                ">",
                "> Everything listed below was written. Anything missing was never reached.",
                "",
            ]
            if failure
            else []
        ),
        "| Project | Sessions | From | To |",
        "| --- | ---: | --- | --- |",
    ]
    for row in sorted(stats, key=lambda s: s["last"], reverse=True):
        name = row["project"]
        lines.append(
            f"| [[{safe_name(name)}/{row['entry']}\\|{name}]] "
            f"| {row['sessions']} | {row['first']:%Y-%m-%d} | {row['last']:%Y-%m-%d} |"
        )
    path = out / "README.md"
    if write_if_changed(path, "\n".join(lines) + "\n") and changed is not None:
        changed.add(path)
    return path


