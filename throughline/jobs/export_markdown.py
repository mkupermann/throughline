#: Split a project file into dated parts once it passes this many bytes.
#: Obsidian's editor becomes visibly sluggish somewhere above a megabyte;
#: this keeps every part comfortably below that.
DEFAULT_SPLIT_BYTES = 1_500_000

#: Cap on a single message's rendered text. Long transcripts are the norm,
#: but a single 200 kB paste helps nobody read the session.
MAX_MESSAGE_CHARS = 12_000

#: Cap on a rendered shell command.
MAX_COMMAND_CHARS = 4_000

#: Tool inputs that name a file the assistant touched.
_PATH_KEYS = ("file_path", "path", "notebook_path", "filePath")

#: Tools whose use means the file changed, not merely that it was read.
_WRITE_TOOLS = {"edit", "write", "notebookedit", "multiedit", "write_file", "str_replace_editor", "apply_patch"}

#: User-message prefixes that are harness injections, not something the
#: person typed. Dropping them is the difference between a readable
#: transcript and a wall of skill boilerplate.
_INJECTED_PREFIXES = (
    "<system-reminder>",
    "<local-command-",
    "<command-name>",
    "<command-message>",
    "Base directory for this skill:",
    "This session is being continued from a previous conversation",
    "Caveat: The messages below were generated by the user while running local commands",
)

#: How the person is labelled in the transcript. A published tool must not
#: carry one person's name in its output, so this is a default with an
#: override rather than a constant.
AUTHOR_ENV = "THROUGHLINE_AUTHOR"
DEFAULT_AUTHOR = "You"


def author() -> str:
    """What to call the person whose prompts these are."""
    return os.environ.get(AUTHOR_ENV, "").strip() or DEFAULT_AUTHOR


_SLUG_STRIP = re.compile(r'[<>:"/\\|?*\x00-\x1f]')


def db_config() -> dict[str, Any]:
    return {
        "host": os.environ.get("PGHOST", "localhost"),
        "port": int(os.environ.get("PGPORT", "5432")),
        "dbname": os.environ.get("PGDATABASE", "throughline"),
        "user": os.environ.get("PGUSER", os.environ.get("USER", "postgres")),
        **({"password": os.environ["PGPASSWORD"]} if os.environ.get("PGPASSWORD") else {}),
    }


