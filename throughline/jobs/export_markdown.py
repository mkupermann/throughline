def safe_name(value: str | None) -> str:
    """Turn a project name into something every filesystem accepts."""
    name = (value or "unknown").strip() or "unknown"
    name = _SLUG_STRIP.sub("-", name)
    name = name.strip(". ")
    return name or "unknown"


def file_url(path: str) -> str:
    """Absolute ``file://`` URL for a path, percent-escaping what matters.

    Obsidian follows these, so a link in the export opens the real file
    even though the file lives outside the vault.
    """
    from urllib.parse import quote

    return "file://" + quote(path, safe="/:")


def resolve_path(raw: str, project_path: str | None) -> str:
    """Make a tool's file argument absolute, using the session's cwd."""
    p = Path(raw).expanduser()
    if p.is_absolute():
        return str(p)
    if project_path:
        return str(Path(project_path).expanduser() / p)
    return str(p)


def link(raw: str, project_path: str | None, *, redact: bool = False) -> str:
    """Markdown link to a file, labelled by its path within the project.

    A bare basename is ambiguous the moment two ``index.html`` files show
    up in one session, so the label keeps whatever part of the path sits
    below the project root.

    Not every session knows where it ran: some adapters record a bare
    project name as ``project_path``, which leaves a relative tool
    argument unresolvable. A ``file://`` URL built from one of those
    points nowhere, so those render as plain code instead — an honest
    path beats a link that fails silently.
    """
    resolved = resolve_path(raw, project_path)
    if redact:
        # Redaction rewrites the home directory out of the path, which makes
        # any URL built from it point nowhere. Show the safe path instead of
        # a link that cannot resolve.
        return f"`{pii.redact(resolved)}`"
    if not Path(resolved).is_absolute():
        return f"`{resolved}`"

    label = Path(resolved).name
    if project_path:
        try:
            label = str(Path(resolved).relative_to(Path(project_path).expanduser()))
        except ValueError:
            pass
    return f"[{label}]({file_url(resolved)})"


_HEADING = re.compile(r"^(#{1,6})(\s)")
_FENCE = re.compile(r"^\s*(```|~~~)")


def demote_headings(text: str) -> str:
    """Push any heading inside a message below the ones the export owns.

    The export uses ``##`` for a session and ``###`` for a turn. A message
    that quotes a Markdown heading — a report the assistant wrote, a README
    it pasted — would otherwise forge a session boundary: on one corpus 22
    such lines appeared in the outline as sessions that never happened, and
    four of them looked like the chronology had broken.

    Fenced blocks are left alone. A shell comment starts with ``#`` at the
    beginning of a line too, and demoting it would corrupt the command.
    """
    out: list[str] = []
    fenced = False
    for line in text.split("\n"):
        if _FENCE.match(line):
            fenced = not fenced
            out.append(line)
            continue
        if not fenced:
            match = _HEADING.match(line)
            if match:
                level = min(len(match.group(1)) + 3, 6)
                out.append("#" * level + line[match.end(1) :])
                continue
        out.append(line)
    return "\n".join(out)


def _clean(text: str, redact: bool) -> str:
    """Run *text* through the PII pass when the export asked for it.

    The same heuristic pass that guards the extraction pipeline: API-key
    shapes, JWTs, bearer headers, ``password=`` assignments, private-key
    blocks, email addresses, and home-directory usernames. It is
    conservative — it will not catch an unusual secret shape — so it
    reduces exposure rather than guaranteeing there is none.
    """
    return pii.redact(text) if redact else text


def prose(text: str, redact: bool, limit: int = MAX_MESSAGE_CHARS) -> str:
    """Prepare a message body for the document it is about to land in.

    Redact if asked, demote any heading so the message cannot forge a
    session boundary, truncate, and then close a code fence the truncation
    cut in half — an unbalanced fence swallows the rest of the file into a
    code block, so the damage is not local to the message.
    """
    body = truncate(demote_headings(_clean(text, redact)), limit)
    if len([line for line in body.split("\n") if _FENCE.match(line)]) % 2:
        body += "\n```"
    return body


def truncate(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + f"\n\n*… {len(text) - limit:,} more characters omitted*"


def block_text(row: dict[str, Any]) -> str:
    """Best available text for a message.

    ``content`` is the flattened text for most adapters; where it is empty
    the text still lives in ``content_blocks``. Thinking blocks are left
    out — they are the assistant's scratchpad, not what it said.

    Ingestion also flattens each tool_use block into ``content`` as a
    ``[Tool: Name]`` stanza followed by its raw arguments. That is the
    same call this exporter renders from ``tool_calls``, so treating it as
    prose would print every command twice — once as JSON, once properly.
    """
    content = (row.get("content") or "").strip()
    if content and not content.startswith("[Tool:"):
        return content
    blocks = row.get("content_blocks")
    if isinstance(blocks, list):
        parts = [str(b.get("text", "")).strip() for b in blocks if isinstance(b, dict) and b.get("type") == "text"]
        joined = "\n\n".join(p for p in parts if p)
        if joined:
            return joined
    return "" if content.startswith("[Tool:") else content


def is_injected(text: str) -> bool:
    stripped = text.lstrip()
    return any(stripped.startswith(prefix) for prefix in _INJECTED_PREFIXES)


#: Models the adapters record that are not a model anyone chose.
_PLACEHOLDER_MODELS = {"<synthetic>", "unknown", ""}


def speaker(conv: dict[str, Any], msg: dict[str, Any]) -> str:
    """Which assistant produced this turn.

    Named per turn rather than per session: a long session routes work to
    whatever model fits — on one corpus a single tool answered from nine
    different models — so the session header cannot say which one wrote a
    given paragraph. Falls back to the session's model when a message does
    not carry its own.
    """
    tool = (conv.get("source_tool") or "").strip()
    model = (msg.get("model") or conv.get("model") or "").strip()
    if model in _PLACEHOLDER_MODELS:
        model = ""
    parts = [p for p in (tool, model) if p]
    return " · ".join(parts) if parts else "KI"


def render_tool_call(call: dict[str, Any], project_path: str | None, *, redact: bool = False) -> tuple[str, str | None]:
    """Render one tool call. Returns (markdown, changed_file_or_None)."""
    name = str(call.get("tool_name") or call.get("name") or "tool")
    payload = call.get("input")
    if not isinstance(payload, dict):
        return f"**{name}**", None

    lower = name.lower()
    note = str(payload.get("description") or "").strip()

    # A shell command is the most legible thing we can show.
    command = payload.get("command")
    if isinstance(command, str) and command.strip():
        head = f"**{name}**" + (f" — {note}" if note else "")
        body = truncate(_clean(command.strip(), redact), MAX_COMMAND_CHARS)
        return f"{head}\n\n```bash\n{body}\n```", None

    # A file argument: link it, and remember it if the file was written.
    for key in _PATH_KEYS:
        raw = payload.get(key)
        if isinstance(raw, str) and raw.strip():
            touched = resolve_path(raw.strip(), project_path) if lower in _WRITE_TOOLS else None
            verb = "writes" if lower in _WRITE_TOOLS else "reads"
            return f"**{name}** {verb} {link(raw.strip(), project_path, redact=redact)}", touched

    # Everything else: a one-line summary of the arguments.
    for key in ("prompt", "query", "pattern", "url", "skill", "message", "subject"):
        raw = payload.get(key)
        if isinstance(raw, str) and raw.strip():
            return f"**{name}** · {prose(raw.strip(), redact, 300)}", None

    compact = _clean(json.dumps(payload, ensure_ascii=False), redact)[:300]
    return f"**{name}** · `{compact}`", None


def render_session(
    conv: dict[str, Any], messages: list[dict[str, Any]], tool_output: int, *, redact: bool = False
) -> str:
    """Render one conversation as a Markdown section."""
    project_path = conv.get("project_path")
    started = conv["started_at"]
    title = (conv.get("summary") or "").strip().splitlines()[0] if conv.get("summary") else ""
    title = _clean(title, redact)[:120] or "Session"

    body: list[str] = []
    touched: list[str] = []
    seen: set[str] = set()

    for msg in messages:
        stamp = msg["created_at"].strftime("%H:%M")
        role = msg["role"]
        text = block_text(msg)

        if role == "user":
            if not text or is_injected(text):
                continue
            body.append(f"### {stamp} · Prompt · {author()}\n\n{prose(text, redact)}")
            continue

        if role == "tool_result":
            if tool_output <= 0 or not text:
                continue
            body.append(
                f"<details><summary>{stamp} · Output</summary>\n\n"
                f"```\n{truncate(_clean(text, redact), tool_output)}\n```\n\n</details>"
            )
            continue

        # assistant — what it said and what it did are separate turns, each
        # naming the model that produced it.
        who = speaker(conv, msg)
        chunk: list[str] = []
        if text:
            chunk.append(f"### {stamp} · Answer · {who}\n\n{prose(text, redact)}")

        actions: list[str] = []
        calls = msg.get("tool_calls")
        if isinstance(calls, list):
            for call in calls:
                if not isinstance(call, dict):
                    continue
                rendered, changed = render_tool_call(call, project_path, redact=redact)
                actions.append(rendered)
                if changed and changed not in seen:
                    seen.add(changed)
                    touched.append(changed)
        if actions:
            chunk.append(f"### {stamp} · Execution · {who}\n\n" + "\n\n".join(actions))

        if chunk:
            body.append("\n\n".join(chunk))

    if not body:
        return ""

    meta = [f"`{conv.get('source_tool') or 'unknown tool'}`"]
    if conv.get("model"):
        meta.append(f"Model `{conv['model']}`")
    if conv.get("git_branch"):
        meta.append(f"Branch `{conv['git_branch']}`")
    meta.append(f"{conv.get('message_count') or len(messages)} messages")

    header = [
        f"## {started.strftime('%Y-%m-%d %H:%M')} — {title}",
        "",
        " · ".join(meta),
        "",
        f"Session `{conv['session_id']}`" + (f" · Path `{_clean(project_path, redact)}`" if project_path else ""),
    ]
    if touched:
        links = ", ".join(link(p, project_path, redact=redact) for p in touched[:40])
        extra = f" *(+{len(touched) - 40} more)*" if len(touched) > 40 else ""
        header += ["", f"**Files changed:** {links}{extra}"]

    return "\n".join(header) + "\n\n" + "\n\n".join(body) + "\n"


