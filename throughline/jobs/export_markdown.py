#!/usr/bin/env python3
"""Export the stored corpus as a Markdown vault, one folder per project.

The database is the archive; Markdown is how you read it five years from
now without this tool installed. Each project becomes a folder, each
folder holds its sessions in one chronological file (oldest first), and
each session reproduces what actually happened: the prompt, the answer,
every tool the assistant reached for, the commands it ran, and a link to
every file it created or changed.

Layout::

    <out>/
      README.md                     index of projects, most recent first
      <Project>/
        <Project>.md                all sessions, oldest first
        <Project> 2026-08-04.md     dated parts once the file grows large
        Memory.md                   extracted memory chunks for the project

Machine-generated conversations (``generated_by IS NOT NULL`` — the
tool's own ``claude -p`` calls) are excluded by default: they hold no
human prompt, and including them buries the sessions you actually had.
``--include-generated`` puts them back.

Usage::

    throughline export-markdown --out ~/Obsidian/Throughline
    throughline export-markdown --out DIR --project throughline
    throughline export-markdown --out DIR --since 2026-01-01
    throughline export-markdown --out DIR --tool-output 400
    throughline export-markdown --out DIR --redact

Exit code: 0 on success, 1 on DB failure, 2 on a usage error.
"""

