def fetch_conversations(conn, *, include_generated: bool, project: str | None, since: str | None) -> list[dict]:
    where = ["TRUE"] if include_generated else ["c.generated_by IS NULL"]
    params: list[Any] = []
    if project:
        where.append("c.project_name = %s")
        params.append(project)
    if since:
        where.append("c.started_at >= %s")
        params.append(since)
    sql = f"""
        SELECT c.id, c.session_id, c.project_name, c.project_path, c.model,
               c.git_branch, c.started_at, c.ended_at, c.message_count,
               c.summary, c.source_tool
          FROM conversations c
         WHERE {" AND ".join(where)}
         ORDER BY c.project_name, c.started_at, c.id
    """
    with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute(sql, params)
        return [dict(r) for r in cur.fetchall()]


def fetch_messages(conn, conversation_id: int) -> list[dict]:
    with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute(
            """
            SELECT role::text AS role, content, content_blocks, tool_calls, created_at
              FROM messages
             WHERE conversation_id = %s
             ORDER BY created_at, id
            """,
            (conversation_id,),
        )
        return [dict(r) for r in cur.fetchall()]


def fetch_memory(conn, project: str) -> list[dict]:
    with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute(
            """
            SELECT id, content, category::text AS category, tags, created_at
              FROM memory_chunks
             WHERE project_name = %s AND status = 'active'
             ORDER BY created_at, id
            """,
            (project,),
        )
        return [dict(r) for r in cur.fetchall()]


